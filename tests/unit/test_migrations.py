"""Alembic schema migrations: every database state celery-manager has ever
produced upgrades to head, concurrently started processes don't trip over
each other, and the shipped revisions agree with the models."""

from __future__ import annotations

import logging
import os
import sys
import threading
from datetime import datetime, timezone

import pytest
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from celery import Celery
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.orm import sessionmaker

from celery_manager import cli
from celery_manager.config import CeleryManagerConfig
from celery_manager.control.schedules import pause_schedule
from celery_manager.db.migrate import (
    BASELINE_REVISION,
    SCHEDULE_PAUSE_REVISION,
    VERSION_TABLE,
    alembic_config,
    head_revision,
    migration_status,
)
from celery_manager.db.models import AuditLog, Base, PeriodicSchedule, TaskRun
from celery_manager.db.session import init_db

ALL_TABLES = {"task_runs", "periodic_schedules", "schedule_overrides", "users", "app_settings", "audit_log"}


def _config(db_url: str, **kwargs) -> CeleryManagerConfig:
    return CeleryManagerConfig(celery_app=Celery("t"), db_url=db_url, secret_key="s", **kwargs)


def _url(tmp_path, name: str = "cm.db") -> str:
    return f"sqlite:///{tmp_path / name}"


def _tables(engine) -> set[str]:
    return set(inspect(engine).get_table_names())


def _schedule_columns(engine) -> set[str]:
    return {c["name"] for c in inspect(engine).get_columns("periodic_schedules")}


def _version(engine) -> str | None:
    with engine.connect() as conn:
        return MigrationContext.configure(conn, opts={"version_table": VERSION_TABLE}).get_current_revision()


def _make_a3_database(db_url: str) -> None:
    """A database exactly as 0.1.0a1-a3 left it: the baseline schema (which
    revision 0001 was autogenerated from the 0.1.0a3 models) with no
    version table, plus some data."""
    engine = create_engine(db_url)
    with engine.begin() as conn:
        command.upgrade(alembic_config(conn), BASELINE_REVISION)
        conn.execute(text(f"DROP TABLE {VERSION_TABLE}"))
        conn.execute(text(
            "INSERT INTO periodic_schedules (name, task_name, schedule_spec, args, kwargs, enabled) "
            "VALUES ('nightly', 'demo.echo', '1d', '[]', '{}', :enabled)"
        ), {"enabled": True})
        conn.execute(text(
            "INSERT INTO task_runs (task_id, task_name, status, args, kwargs, retry_count) "
            "VALUES ('abc', 'demo.echo', 'succeeded', '[]', '{}', 0)"
        ))
    engine.dispose()


def _assert_at_head_with_data(engine) -> None:
    assert _version(engine) == head_revision()
    assert ALL_TABLES <= _tables(engine)
    assert {"paused_at", "paused_by"} <= _schedule_columns(engine)
    with sessionmaker(bind=engine)() as session:
        assert session.query(TaskRun).one().task_id == "abc"
        assert session.query(PeriodicSchedule).one().name == "nightly"


