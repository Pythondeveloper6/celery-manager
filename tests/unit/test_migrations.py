def test_auto_migrate_off_leaves_an_empty_database_untouched(tmp_path, caplog):
    with caplog.at_level(logging.WARNING, logger="celery_manager.db.session"):
        engine = init_db(_config(_url(tmp_path), auto_migrate=False))
    assert _tables(engine) == set()
    assert "auto_migrate is off" in caplog.text


def test_auto_migrate_off_leaves_an_old_database_untouched(tmp_path, caplog):
    url = _url(tmp_path)
    _make_a3_database(url)
    with caplog.at_level(logging.WARNING, logger="celery_manager.db.session"):
        engine = init_db(_config(url, auto_migrate=False))
    assert VERSION_TABLE not in _tables(engine)
    assert "paused_at" not in _schedule_columns(engine)
    assert "unversioned" in caplog.text


def test_auto_migrate_off_is_silent_when_current(tmp_path, caplog):
    url = _url(tmp_path)
    init_db(_config(url)).dispose()
    with caplog.at_level(logging.WARNING, logger="celery_manager.db.session"):
        init_db(_config(url, auto_migrate=False))
    assert caplog.text == ""


# --- CLI ---------------------------------------------------------------------


def _run_cli(monkeypatch, *argv: str) -> int:
    monkeypatch.setattr(sys, "argv", ["celery-manager", *argv])
    with pytest.raises(SystemExit) as exc:
        cli.main()
    return exc.value.code


def test_cli_migrate_check_then_upgrade(tmp_path, monkeypatch, capsys):
    url = _url(tmp_path)
    _make_a3_database(url)

    assert _run_cli(monkeypatch, "migrate", "--db-url", url, "--check") == 1
    out = capsys.readouterr().out
    assert "unversioned" in out and "needs an upgrade" in out
    assert VERSION_TABLE not in _tables(create_engine(url))

    assert _run_cli(monkeypatch, "migrate", "--db-url", url) == 0
    assert f"Upgraded to {head_revision()}" in capsys.readouterr().out
    _assert_at_head_with_data(create_engine(url))

    assert _run_cli(monkeypatch, "migrate", "--db-url", url, "--check") == 0
    assert "up to date" in capsys.readouterr().out
    assert _run_cli(monkeypatch, "migrate", "--db-url", url) == 0
    assert "nothing to do" in capsys.readouterr().out


def test_migration_status_reports_empty_database(tmp_path):
    status = migration_status(create_engine(_url(tmp_path)))
    assert status.current is None and not status.legacy and not status.up_to_date


# --- revisions vs models -------------------------------------------------------


def test_models_and_migrations_agree(tmp_path):
    """Upgrading an empty database to head yields exactly the models'
    schema. If this fails after a model change, generate a revision (see
    docs/contributing.md, "Schema changes")."""
    engine = create_engine(_url(tmp_path))
    with engine.begin() as conn:
        command.upgrade(alembic_config(conn), "head")
    with engine.connect() as conn:
        context = MigrationContext.configure(conn, opts={"compare_type": True, "version_table": VERSION_TABLE})
        assert compare_metadata(context, Base.metadata) == []


def test_revision_history_is_linear():
    """Two branches each adding a revision on the same parent produce two
    heads; re-point the later one's down_revision after merging."""
    script = ScriptDirectory.from_config(alembic_config())
    assert len(script.get_heads()) == 1
    assert script.get_revision(SCHEDULE_PAUSE_REVISION).down_revision == BASELINE_REVISION


