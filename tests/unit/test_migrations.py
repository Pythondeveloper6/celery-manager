def test_versioned_database_upgrades_from_an_older_revision(tmp_path):
    url = _url(tmp_path)
    engine = create_engine(url)
    with engine.begin() as conn:
        command.upgrade(alembic_config(conn), BASELINE_REVISION)
    engine.dispose()

    engine = init_db(_config(url))
    assert _version(engine) == head_revision()
    assert {"paused_at", "paused_by"} <= _schedule_columns(engine)


def test_re_running_init_db_is_a_no_op(tmp_path):
    url = _url(tmp_path)
    _make_a3_database(url)
    init_db(_config(url)).dispose()
    engine = init_db(_config(url))
    init_db(_config(url)).dispose()
    _assert_at_head_with_data(engine)


def test_concurrent_init_db_calls_all_succeed(tmp_path):
    """API, worker and listener starting at once against one fresh database."""
    url = _url(tmp_path)
    errors: list[Exception] = []
    barrier = threading.Barrier(6)

    def start():
        try:
            barrier.wait()
            init_db(_config(url)).dispose()
        except Exception as exc:  # noqa: BLE001 - surfaced by the assert below
            errors.append(exc)

    threads = [threading.Thread(target=start) for _ in range(6)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert errors == []
    assert _version(create_engine(url)) == head_revision()


def test_host_applications_own_alembic_version_table_is_left_alone(tmp_path):
    url = _url(tmp_path)
    engine = create_engine(url)
    with engine.begin() as conn:
        conn.execute(text("CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL)"))
        conn.execute(text("INSERT INTO alembic_version VALUES ('hostapp123')"))
    engine.dispose()

    engine = init_db(_config(url))
    assert _version(engine) == head_revision()
    with engine.connect() as conn:
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == "hostapp123"


